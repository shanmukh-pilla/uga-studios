import type { Mood } from '../../data/site'
import bankDay from '../../assets/atmosphere/clouds-bank-day.webp'
import bankDusk from '../../assets/atmosphere/clouds-bank-dusk.webp'
import bankNight from '../../assets/atmosphere/clouds-bank-night.webp'
import puffsDay from '../../assets/atmosphere/clouds-puffs-day.webp'
import puffsDusk from '../../assets/atmosphere/clouds-puffs-dusk.webp'
import puffsNight from '../../assets/atmosphere/clouds-puffs-night.webp'
import wispsDay from '../../assets/atmosphere/clouds-wisps-day.webp'
import wispsDusk from '../../assets/atmosphere/clouds-wisps-dusk.webp'

/*
 * Cloud layers are generated by scripts/generate-clouds.py: horizontally
 * tileable RGBA WebP, 2400px wide, rendered in three lighting palettes.
 */

export type CloudKind = 'bank' | 'puffs' | 'wisps'
type Palette = 'day' | 'dusk' | 'night'

const sources: Record<CloudKind, Partial<Record<Palette, string>> & { day: string; ratio: number }> = {
  bank: { day: bankDay, dusk: bankDusk, night: bankNight, ratio: 900 / 2400 },
  puffs: { day: puffsDay, dusk: puffsDusk, night: puffsNight, ratio: 800 / 2400 },
  wisps: { day: wispsDay, dusk: wispsDusk, ratio: 700 / 2400 },
}

const paletteFor: Record<Mood, Palette> = {
  day: 'day',
  morning: 'day',
  dawn: 'day',
  dusk: 'dusk',
  night: 'night',
}

export function cloudLayer(kind: CloudKind, mood: Mood) {
  const set = sources[kind]
  const palette = paletteFor[mood]
  return { src: set[palette] ?? set.dusk ?? set.day, ratio: set.ratio }
}
